const multipart = (fields: Record<string, any>, files: File[] = []) => {
  const fd = new FormData();
  for (const [k, v] of Object.entries(fields)) {
    if (v === undefined || v === null || v === "") continue;
    fd.append(k, String(v));
  }
  files.forEach((f) => fd.append("documents", f));
  return fd;
};

